// T-012 — очередь операций одной доски (I6, docs/spec/consistency-model.md
// § 8, доказательство Т7⇒I6: «дельты одной доски обрабатываются
// последовательно» — явное допущение модели, без которого лимит голосов
// (V7, ops/votes.ts) не держится под конкурентными vote с разных вкладок
// одного участника: оба сообщения могли бы пройти checkVoteLimit до того,
// как любое из них попадёт в журнал).
//
// FIFO по boardId: следующий fn для той же доски не начинает выполняться,
// пока не завершится (успешно или с ошибкой) предыдущий; доски независимы
// друг от друга. Ошибка в одном fn не блокирует очередь навсегда — тот же
// tail всегда переходит дальше как resolved, независимо от исхода. Один
// экземпляр на процесс (не на подключение) — единственный процесс сервера,
// чего достаточно для MVP (горизонтальное масштабирование — вне MVP,
// CLAUDE.md § 2). Контракт и обоснование каждого пункта — board-queue.test.ts.

export interface BoardQueue {
  /** Выполняет `fn` для данной доски, строго после завершения предыдущего `run` этой же доски. */
  run(boardId: string, fn: () => Promise<void>): Promise<void>;
}

export function createBoardQueue(): BoardQueue {
  const tails = new Map<string, Promise<void>>();

  return {
    run(boardId: string, fn: () => Promise<void>): Promise<void> {
      const previous = tails.get(boardId) ?? Promise.resolve();
      const tail = previous.then(fn, fn);
      // Хвост в карте всегда resolved (никогда не пробрасывает ошибку) —
      // иначе упавший fn навсегда заблокировал бы очередь этой доски для
      // всех последующих run(). Вызывающий получает исход именно fn через
      // возвращаемый tail, не через это значение.
      tails.set(
        boardId,
        tail.then(
          () => undefined,
          () => undefined,
        ),
      );
      return tail;
    },
  };
}
