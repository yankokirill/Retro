// T-012 — очередь операций одной доски (I6, docs/spec/consistency-model.md
// § 8, доказательство Т7⇒I6: «дельты одной доски обрабатываются
// последовательно» — явное допущение модели, без которого лимит голосов
// (V7, ops/votes.ts) не держится под конкурентными vote с разных вкладок
// одного участника: оба сообщения могли бы пройти checkVoteLimit до того,
// как любое из них попадёт в журнал).
//
// Эта версия — СКВОЗНАЯ: run() вызывает fn немедленно, без упорядочивания.
// Сделано намеренно отдельным коммитом от самого исправления гонки — чтобы
// сначала тестами зафиксировать текущее (небезопасное) поведение, потом
// одной точечной правкой превратить run() в реальный FIFO по boardId и
// увидеть эти же тесты позеленевшими. См. board-queue.test.ts.

export interface BoardQueue {
  /** Выполняет `fn` для данной доски. Эта версия — без упорядочивания между вызовами. */
  run(boardId: string, fn: () => Promise<void>): Promise<void>;
}

export function createBoardQueue(): BoardQueue {
  return {
    run(_boardId: string, fn: () => Promise<void>): Promise<void> {
      return fn();
    },
  };
}
